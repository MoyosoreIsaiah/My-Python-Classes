# There are different data types in python

# The first one is string(" ")

car = "rolls-royce"
print(car)

# The second one is integers(whole numbers)
amount = 2+2
print(amount)

# The third one is float: They are decimal numbers(.)
price = 1500.00
print(price)

cgpa = 4.5
print(type(cgpa))

# boolean: uses true or false
is_student = False
print(type(is_student))

# checking the/ data type
food = "yam"
print(type(food))
